CREATE TABLE categories (
    category_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR2(60) NOT NULL UNIQUE
);

CREATE TABLE products (
    product_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name  VARCHAR2(100) NOT NULL,
    category_id   NUMBER NOT NULL,
    unit_price    NUMBER(10,2) NOT NULL CHECK (unit_price >= 0),
    quantity      NUMBER(10) DEFAULT 0 NOT NULL CHECK (quantity >= 0),
    reorder_level NUMBER(10) DEFAULT 5 NOT NULL CHECK (reorder_level >= 0),
    created_at    DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT fk_products_category
        FOREIGN KEY (category_id) REFERENCES categories(category_id)
);

CREATE TABLE stock_transactions (
    transaction_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id       NUMBER NOT NULL,
    transaction_type VARCHAR2(3) NOT NULL
        CHECK (transaction_type IN ('IN', 'OUT')),
    quantity         NUMBER(10) NOT NULL CHECK (quantity > 0),
    transaction_date DATE DEFAULT SYSDATE NOT NULL,
    remarks           VARCHAR2(200),
    CONSTRAINT fk_transaction_product
        FOREIGN KEY (product_id) REFERENCES products(product_id)
);

CREATE INDEX idx_products_category ON products(category_id);
CREATE INDEX idx_transactions_product ON stock_transactions(product_id);

